def split_into_chunks(text):

    text = str(text).strip()

    if not text:
        return []

    text = re.sub(
        r"\s+",
        " ",
        text
    )

    chunks = re.split(
        r"(?<=[.!?])\s+",
        text
    )

    chunks = [
        chunk.strip()
        for chunk in chunks
        if len(chunk.strip()) >= 8
    ]

    if not chunks:
        chunks = [text]

    return chunks


# ============================================================
# KEYWORD PROCESSING
# ============================================================

STOPWORDS = {
    "the", "and", "for", "with",
    "from", "that", "this", "have",
    "has", "had", "was", "were",
    "are", "been", "being", "into",
    "their", "there", "they", "them",
    "our", "your", "you", "who",
    "while", "during", "part", "work",
    "worked", "working", "experience",
    "responsible", "responsibility"
}


def tokenize(text):

    words = re.findall(
        r"\b[a-zA-Z][a-zA-Z-]+\b",
        text.lower()
    )

    return {
        word
        for word in words
        if word not in STOPWORDS
        and len(word) >= 3
    }


def keyword_overlap(
    text,
    capability
):

    text_words = tokenize(text)

    capability_words = tokenize(
        capability
    )

    if not capability_words:
        return 0.0

    overlap = (
        len(
            text_words &
            capability_words
        )
        /
        len(capability_words)
    )

    return min(
        overlap,
        1.0
    )


# ============================================================
# EVIDENCE SCORING
# ============================================================

def evidence_strength(text):

    score = 0.0

    text_lower = text.lower()

    # Numbers
    if re.search(
        r"\b\d[\d,]*\b",
        text
    ):
        score += 0.30

    # Duration
    if re.search(
        r"\b\d+\s*"
        r"(year|years|month|months|"
        r"week|weeks|day|days)\b",
        text_lower
    ):
        score += 0.20

    # People / teams
    if re.search(
        r"\b(team|people|volunteers|"
        r"employees|customers|clients|"
        r"vendors|suppliers|students|"
        r"members|participants)\b",
        text_lower
    ):
        score += 0.20

    # Action verbs
    if re.search(
        r"\b(manage|managed|lead|led|"
        r"organize|organized|coordinate|"
        r"coordinated|built|developed|"
        r"created|handled|planned|"
        r"negotiated|implemented|"
        r"supervised|delivered|improved)\b",
        text_lower
    ):
        score += 0.20

    # Outcomes
    if re.search(
        r"\b(improved|increased|reduced|"
        r"completed|delivered|achieved|"
        r"successfully|result|outcome)\b",
        text_lower
    ):
        score += 0.10

    return min(
        score,
        1.0
    )


# ============================================================
# CONFIDENCE
# ============================================================

def calculate_confidence(
    semantic_score,
    keyword_score,
    evidence_score
):

    confidence = (

        SEMANTIC_WEIGHT
        * semantic_score

        +

        KEYWORD_WEIGHT
        * keyword_score

        +

        EVIDENCE_WEIGHT
        * evidence_score
    )

    return round(
        float(
            np.clip(
                confidence,
                0.0,
                1.0
            )
            * 100
        ),
        1
    )


