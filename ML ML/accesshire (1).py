def infer_capabilities_api(
    text,
    top_k=DEFAULT_TOP_K,
    confidence_threshold=55.0
):

    if not isinstance(
        text,
        str
    ):

        raise TypeError(
            "text must be a string."
        )

    if not text.strip():

        return []

    chunks = split_into_chunks(
        text
    )

    if not chunks:

        return []

    # --------------------------------------------------------
    # Encode user experience
    # --------------------------------------------------------

    chunk_embeddings = api_model.encode(
        chunks,
        batch_size=32,
        normalize_embeddings=True,
        show_progress_bar=False
    )

    # --------------------------------------------------------
    # Semantic similarity
    # --------------------------------------------------------

    similarity_matrix = (
        chunk_embeddings
        @
        capability_embeddings.T
    )

    results = []

    # --------------------------------------------------------
    # Find strongest evidence for every capability
    # --------------------------------------------------------

    for capability_idx, capability in enumerate(
        capability_names
    ):

        scores = similarity_matrix[
            :,
            capability_idx
        ]

        best_idx = int(
            np.argmax(scores)
        )

        best_chunk = chunks[
            best_idx
        ]

        semantic_score = float(
            scores[best_idx]
        )

        keyword_score = keyword_overlap(
            best_chunk,
            capability
        )

        evidence_score = evidence_strength(
            best_chunk
        )

        confidence = calculate_confidence(
            semantic_score,
            keyword_score,
            evidence_score
        )

        if confidence >= confidence_threshold:

            results.append({

                "capability":
                    capability,

                "confidence":
                    confidence,

                "semantic_score":
                    round(
                        semantic_score,
                        4
                    ),

                "keyword_score":
                    round(
                        keyword_score,
                        4
                    ),

                "evidence_score":
                    round(
                        evidence_score,
                        4
                    ),

                "evidence_snippet":
                    best_chunk
            })

    results.sort(
        key=lambda x: x["confidence"],
        reverse=True
    )

    return results[:top_k]


