# 6. KEYWORD OVERLAP
# ============================================================

STOPWORDS = {
    "the", "and", "for", "with",
    "from", "that", "this", "have",
    "has", "had", "was", "were",
    "are", "been", "being", "into",
    "their", "there", "they", "them",
    "our", "your", "you", "who",
    "while", "during", "part", "work",
    "worked", "working", "experience",
    "responsible", "responsibility"
}


def tokenize(text):

    words = re.findall(
        r"\b[a-zA-Z][a-zA-Z-]+\b",
        text.lower()
    )

    return {
        word
        for word in words
        if word not in STOPWORDS
        and len(word) >= 3
    }


def keyword_overlap(
    text,
    capability
):

    text_words = tokenize(text)
    capability_words = tokenize(capability)

    if not capability_words:
        return 0.0

    overlap = (
        len(
            text_words &
            capability_words
        )
        /
        len(capability_words)
    )

    return min(
        overlap,
        1.0
    )


