@app.post("/infer-capabilities")
def infer_capabilities(request: InferenceRequest):

    text = request.text.strip()

    if not text:
        raise HTTPException(
            status_code=400,
            detail="Text cannot be empty."
        )

    # Generate query embedding
    query_embedding = model.encode(
        [text],
        convert_to_numpy=True,
        normalize_embeddings=True
    )[0]

    # Semantic similarity
    similarities = np.dot(
        capability_embeddings_normalized,
        query_embedding
    )

    # Top candidates
    candidate_indices = np.argsort(
        similarities
    )[::-1][:request.top_k]

    results = []

    text_lower = text.lower()

    for idx in candidate_indices:

        capability = str(
            capability_names[idx]
        )

        semantic_score = float(
            similarities[idx]
        )

        # Basic keyword signal
        capability_words = re.findall(
            r"[a-zA-Z]+",
            capability.lower()
        )

        matched_words = [
            word
            for word in capability_words
            if len(word) > 3 and word in text_lower
        ]

        keyword_score = min(
            len(matched_words) / max(
                len(capability_words),
                1
            ),
            1.0
        )

        # Evidence signal
        evidence_score = (
            0.7 * max(
                semantic_score,
                0
            )
            +
            0.15 * keyword_score
            +
            0.15 * (
                1.0
                if matched_words
                else 0.0
            )
        )

        confidence = round(
            max(
                0,
                min(
                    evidence_score * 100,
                    99.9
                )
            ),
            2
        )

        results.append({
            "capability": capability,
            "confidence": confidence,
            "semantic_score": round(
                semantic_score,
                4
            ),
            "keyword_score": round(
                keyword_score,
                4
            ),
            "evidence_score": round(
                evidence_score,
                4
            ),
            "evidence_snippet": text
        })

    return {
        "success": True,
        "input": text,
        "capabilities": results,
        "count": len(results),
        "model": "accesshire-mpnet-final",
        "taxonomy_size": len(capability_names)
    }

