def deduplicate_capability_results(
    candidates,
    similarity_threshold=0.82,
    top_k=8
):
    """
    Removes highly similar capability results.

    Example:
        budget management
        manage budgets

    Only the stronger result is retained.
    """

    if not candidates:
        return []

    # Strongest first
    candidates = sorted(
        candidates,
        key=lambda x: x["confidence"],
        reverse=True
    )

    selected = []

    for candidate in candidates:

        candidate_idx = candidate[
            "capability_index"
        ]

        duplicate = False

        for existing in selected:

            existing_idx = existing[
                "capability_index"
            ]

            similarity = float(
                np.dot(
                    capability_embeddings[
                        candidate_idx
                    ],

                    capability_embeddings[
                        existing_idx
                    ]
                )
            )

            if similarity >= similarity_threshold:

                duplicate = True
                break

        if duplicate:
            continue

        selected.append(
            candidate
        )

        if len(selected) >= top_k:
            break

    return selected


