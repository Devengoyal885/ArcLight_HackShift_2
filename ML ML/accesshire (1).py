import numpy as np
import re


# ============================================================
# 1. CAPABILITY TEXT SIMILARITY
# ============================================================

def capability_text_similarity(
    capability_a,
    capability_b
):
    """
    Simple lexical similarity between two capability names.
    Used only to prevent duplicate/near-duplicate results.
    """

    def words(text):

        return set(
            re.findall(
                r"\b[a-zA-Z]{3,}\b",
                text.lower()
            )
        )

    a = words(capability_a)
    b = words(capability_b)

    if not a or not b:
        return 0.0

    intersection = len(a & b)
    union = len(a | b)

    return intersection / union


# ============================================================
# 2. DIVERSITY-AWARE RERANKING
# ============================================================

def diversity_rerank(
    candidates,
    top_k=8,
    similarity_penalty=0.35
):
    """
    Select high-confidence capabilities while avoiding
    multiple near-duplicate capabilities.

    candidates must contain:
        capability
        confidence
    """

    if not candidates:
        return []

    candidates = sorted(
        candidates,
        key=lambda x: x["confidence"],
        reverse=True
    )

    selected = []

    while (
        len(selected) < top_k
        and candidates
    ):

        best_candidate = None
        best_score = -float("inf")

        for candidate in candidates:

            if candidate in selected:
                continue

            score = candidate["confidence"]

            # Penalize candidates that are very similar
            # to already-selected capabilities.
            if selected:

                max_similarity = max(
                    capability_text_similarity(
                        candidate["capability"],
                        selected_item["capability"]
                    )
                    for selected_item in selected
                )

                score -= (
                    similarity_penalty
                    * max_similarity
                    * 100
                )

            else:

                max_similarity = 0.0

            if score > best_score:

                best_score = score
                best_candidate = candidate

        if best_candidate is None:
            break

        selected.append(
            best_candidate
        )

        candidates.remove(
            best_candidate
        )

    # Return in confidence order
    selected.sort(
        key=lambda x: x["confidence"],
        reverse=True
    )

    return selected


