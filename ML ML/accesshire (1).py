def split_into_chunks(text):

    text = str(text).strip()

    if not text:
        return []

    # Normalize whitespace
    text = re.sub(
        r"\s+",
        " ",
        text
    )

    # Split on sentence boundaries
    chunks = re.split(
        r"(?<=[.!?])\s+",
        text
    )

    # Remove very short chunks
    chunks = [
        chunk.strip()
        for chunk in chunks
        if len(chunk.strip()) >= 8
    ]

    # If no sentence boundary exists,
    # use the complete text
    if not chunks:
        chunks = [text]

    return chunks


