# ============================================================
# 1. IMPROVED TEXT CHUNKING
# ============================================================

def create_experience_chunks(text):

    text = str(text).strip()

    if not text:
        return []

    # Normalize whitespace
    text = re.sub(
        r"\s+",
        " ",
        text
    )

    # --------------------------------------------------------
    # First: normal sentences
    # --------------------------------------------------------

    sentences = re.split(
        r"(?<=[.!?])\s+",
        text
    )

    chunks = []

    for sentence in sentences:

        sentence = sentence.strip()

        if not sentence:
            continue

        # Keep the complete sentence
        chunks.append(sentence)

        # ----------------------------------------------------
        # Split comma-separated action phrases
        # ----------------------------------------------------

        comma_parts = [
            part.strip()
            for part in sentence.split(",")
            if len(part.strip()) >= 5
        ]

        if len(comma_parts) > 1:

            # Try to preserve the main action verb.
            verb_match = re.search(
                r"\b("
                r"manage|managed|"
                r"organize|organized|"
                r"coordinate|coordinated|"
                r"lead|led|"
                r"handle|handled|"
                r"plan|planned|"
                r"develop|developed|"
                r"build|built|"
                r"create|created|"
                r"run|"
                r"support|supported|"
                r"maintain|maintained|"
                r"supervise|supervised|"
                r"negotiate|negotiated|"
                r"deliver|delivered|"
                r"implement|implemented"
                r")\b",
                sentence.lower()
            )

            if verb_match:

                verb = verb_match.group(1)

                for part in comma_parts:

                    part_lower = part.lower()

                    # Don't duplicate the original action phrase
                    if re.search(
                        rf"\b{re.escape(verb)}\b",
                        part_lower
                    ):
                        phrase = part

                    else:
                        phrase = (
                            verb.capitalize()
                            + " "
                            + part
                        )

                    if len(phrase) >= 8:

                        chunks.append(
                            phrase.strip()
                        )

        # ----------------------------------------------------
        # Split simple "X and Y" structures
        # ----------------------------------------------------

        and_parts = re.split(
            r"\s+\band\b\s+",
            sentence,
            flags=re.IGNORECASE
        )

        if len(and_parts) > 1:

            verb_match = re.search(
                r"\b("
                r"manage|managed|"
                r"organize|organized|"
                r"coordinate|coordinated|"
                r"lead|led|"
                r"handle|handled|"
                r"plan|planned|"
                r"develop|developed|"
                r"build|built|"
                r"create|created|"
                r"run|"
                r"support|supported|"
                r"maintain|maintained|"
                r"supervise|supervised|"
                r"negotiate|negotiated"
                r")\b",
                sentence.lower()
            )

            if verb_match:

                verb = verb_match.group(1)

                for part in and_parts:

                    part = part.strip()

                    if len(part) < 5:
                        continue

                    if re.search(
                        rf"\b{re.escape(verb)}\b",
                        part.lower()
                    ):
                        phrase = part

                    else:
                        phrase = (
                            verb.capitalize()
                            + " "
                            + part
                        )

                    if len(phrase) >= 8:

                        chunks.append(
                            phrase.strip()
                        )

    # --------------------------------------------------------
    # Remove duplicates
    # --------------------------------------------------------

    final_chunks = []

    seen = set()

    for chunk in chunks:

        normalized = re.sub(
            r"\s+",
            " ",
            chunk.lower()
        ).strip()

        if normalized in seen:
            continue

        seen.add(normalized)

        final_chunks.append(
            chunk
        )

    return final_chunks


